#!/usr/bin/env ruby
require "minitest/autorun"
require "fileutils"
require "tmpdir"
require_relative "isolated_git"
require_relative "lefthook_binary"

# LefthookBinary.locate prefers the native lefthook binary over the RubyGems wrapper script, which
# costs a Ruby start-up on every call.
class LefthookBinaryTest < Minitest::Test
  PLATFORM = "lefthook-darwin-arm64".freeze
  WRAPPER = "#!/usr/bin/env ruby\n#\n# This file was generated by RubyGems.\nrequire 'rubygems'\n".freeze

  def setup
    @dir = Dir.mktmpdir
    @saved_lefthook_bin = ENV.delete("LEFTHOOK_BIN")
  end

  def teardown
    ENV["LEFTHOOK_BIN"] = @saved_lefthook_bin
    FileUtils.rm_rf(@dir)
  end

  def test_a_rubygems_wrapper_on_path_resolves_to_its_native_binary
    native = write_gem("lefthook-2.2.2")

    assert_equal(native, locate(write_executable("bin/lefthook", WRAPPER), gem_dir: gem_dir("lefthook-2.2.2")))
  end

  def test_the_gem_rubygems_would_run_wins_over_the_wrappers_own_gem_home
    write_gem("home/lefthook-2.1.2")
    newest = write_gem("ruby/lefthook-2.2.2")
    wrapper = write_executable("home/bin/lefthook", WRAPPER)

    assert_equal(newest, locate(wrapper, gem_dir: gem_dir("ruby/lefthook-2.2.2")))
  end

  def test_a_native_binary_on_path_is_returned_unchanged
    native = write_executable("usr/lefthook", "\x7fELF native")

    assert_equal(native, locate(native, gem_dir: ->(*) { flunk("RubyGems must not be asked") }))
  end

  def test_a_wrapper_without_an_installed_gem_is_returned_as_is
    wrapper = write_executable("bin/lefthook", WRAPPER)
    missing = ->(*) { raise Gem::MissingSpecError.new("lefthook", ">= 0") }

    assert_equal(wrapper, locate(wrapper, gem_dir: missing))
  end

  def test_a_wrapper_without_a_native_binary_for_this_platform_is_returned_as_is
    FileUtils.mkdir_p(File.join(@dir, "lefthook-2.2.2", "libexec"))
    wrapper = write_executable("bin/lefthook", WRAPPER)

    assert_equal(wrapper, locate(wrapper, gem_dir: gem_dir("lefthook-2.2.2")))
  end

  def test_lefthook_bin_still_wins
    chosen = write_executable("chosen/lefthook", "x")
    ENV["LEFTHOOK_BIN"] = chosen

    assert_equal(chosen, locate(write_executable("bin/lefthook", WRAPPER), gem_dir: gem_dir("lefthook-2.2.2")))
  end

  def test_the_platform_directory_follows_the_host_os_and_cpu
    names = [ %w[darwin23 arm64], %w[linux-gnu x86_64], %w[linux aarch64] ].map do |os, cpu|
      LefthookBinary.platform_directory(os, cpu)
    end

    assert_equal(%w[lefthook-darwin-arm64 lefthook-linux-x64 lefthook-linux-arm64], names)
  end

  private

  def locate(on_path, gem_dir:)
    LefthookBinary.locate(path_lookup: -> { on_path }, gem_dir: gem_dir, platform: PLATFORM)
  end

  def gem_dir(name)
    ->(*) { File.join(@dir, name) }
  end

  def write_gem(name)
    write_executable("#{name}/libexec/#{PLATFORM}/lefthook", "\x7fELF native")
  end

  def write_executable(relative, body)
    path = File.join(@dir, relative)
    FileUtils.mkdir_p(File.dirname(path))
    File.write(path, body)
    File.chmod(0o755, path)
    path
  end
end
