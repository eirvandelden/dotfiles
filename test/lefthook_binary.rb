require "rbconfig"

module LefthookBinary
  RV_GLOB = File.join(
    Dir.home, ".local/share/rv/rubies/*/lib/ruby/gems/*/gems/lefthook-*/libexec/lefthook-darwin-arm64/lefthook"
  )
  MISSING_MESSAGE =
    "lefthook not found: not on PATH (checked LEFTHOOK_BIN and `which lefthook`) " \
    "and no rv install matched #{RV_GLOB}"

  CPUS = { "arm64" => "arm64", "aarch64" => "arm64", "x86_64" => "x64" }.freeze
  WRAPPER_MARKER = "This file was generated by RubyGems".freeze

  # `which lefthook` finds a RubyGems wrapper script on a machine that installed the gem. Running it
  # starts Ruby (75 ms against 13 ms for the native binary), so the wrapper is swapped for the gem's
  # own native binary when RubyGems can name it.
  def self.locate(path_lookup: method(:which), gem_dir: method(:rubygems_dir), platform: platform_directory)
    from_env || from_path(path_lookup.call, gem_dir, platform) || Dir.glob(RV_GLOB).find { |f| File.executable?(f) }
  end

  def self.from_env
    ENV["LEFTHOOK_BIN"] if ENV["LEFTHOOK_BIN"] && File.executable?(ENV["LEFTHOOK_BIN"])
  end

  def self.from_path(found, gem_dir, platform)
    return unless found
    return found unless wrapper?(found)

    native_in(gem_dir, platform) || found
  end

  def self.which
    found = `which lefthook 2>/dev/null`.strip
    found unless found.empty?
  end

  def self.wrapper?(path)
    head = File.binread(path, 512)
    head.start_with?("#!") && head.include?(WRAPPER_MARKER)
  end

  # The gem directory of the lefthook RubyGems would run, across every gem home on GEM_PATH.
  def self.rubygems_dir
    Gem::Specification.find_by_name("lefthook").full_gem_path
  end

  def self.native_in(gem_dir, platform)
    binary = File.join(gem_dir.call, "libexec", platform, "lefthook")
    binary if File.executable?(binary)
  rescue Gem::MissingSpecError
    nil
  end

  def self.platform_directory(host_os = RbConfig::CONFIG["host_os"], host_cpu = RbConfig::CONFIG["host_cpu"])
    "lefthook-#{host_os[/darwin|linux/]}-#{CPUS.fetch(host_cpu)}"
  end
end
